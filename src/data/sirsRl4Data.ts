/**
 * Generates Top 10 Inpatient Morbidity diseases sorted by total live + dead patients (hidupMatiTotal)
 * Exactly per SIRS 6.3 Formulir RL 4.2 format
 */
export const getSirsRl42Top10 = (sourceRows: SirsRl41Row[] = INITIAL_SIRS_63_RL41_DATA): SirsRl42Top10Row[] => {
  const sorted = [...sourceRows].sort((a, b) => b.hidupMatiTotal - a.hidupMatiTotal);
  return sorted.slice(0, 10).map((row, index) => ({
    rank: index + 1,
    code: row.code,
    name: row.name,
    hidupMatiL: row.hidupMatiL,
    hidupMatiP: row.hidupMatiP,
    hidupMatiTotal: row.hidupMatiTotal,
    matiL: row.matiL,
    matiP: row.matiP,
    matiTotal: row.matiTotal,
  }));
};

/**
 * Generates Top 10 Inpatient Mortality diseases sorted by total dead patients (matiTotal)
 * Exactly per SIRS 6.3 Formulir RL 4.3 format
 */
export const getSirsRl43Top10Death = (sourceRows: SirsRl41Row[] = INITIAL_SIRS_63_RL41_DATA): SirsRl43Top10DeathRow[] => {
  const sorted = [...sourceRows].sort((a, b) => {
    if (b.matiTotal !== a.matiTotal) {
      return b.matiTotal - a.matiTotal;
    }
    return b.hidupMatiTotal - a.hidupMatiTotal;
  });
  return sorted.slice(0, 10).map((row, index) => ({
    rank: index + 1,
    code: row.code,
    name: row.name,
    hidupMatiL: row.hidupMatiL,
    hidupMatiP: row.hidupMatiP,
    hidupMatiTotal: row.hidupMatiTotal,
    matiL: row.matiL,
    matiP: row.matiP,
    matiTotal: row.matiTotal,
  }));
};

